//! Generates and checks the TypeScript bindings committed under
//! `apps/ui/src/gen`.
//!
//! This is the only writer of that directory. `scripts/check-bindings.sh`
//! runs this test and fails when the checked-in output differs.

use std::fs;
use std::path::{Path, PathBuf};

use h4rn_protocol::{ClientFrame, ServerFrame};
use ts_rs::TS;

fn gen_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../apps/ui/src/gen")
}

fn remove_generated_types(dir: &Path) {
    for entry in fs::read_dir(dir).expect("read gen directory") {
        let entry = entry.expect("read entry");
        let path = entry.path();
        if path.extension().and_then(|ext| ext.to_str()) == Some("ts") {
            fs::remove_file(path).expect("remove stale binding");
        }
    }
}

fn write_barrel(dir: &Path) {
    let mut names: Vec<String> = fs::read_dir(dir)
        .expect("read gen directory")
        .filter_map(|entry| {
            let path = entry.ok()?.path();
            let name = path.file_stem()?.to_str()?.to_owned();
            (path.extension().and_then(|ext| ext.to_str()) == Some("ts")
                && name != "index"
                && !name.contains('.'))
            .then_some(name)
        })
        .collect();
    names.sort();

    let mut barrel = String::from(
        "// This file is generated by `crates/h4rn-protocol/tests/bindings.rs`.\n\
         // Do not edit it by hand; run `cargo test -p h4rn-protocol` instead.\n\n",
    );
    for name in names {
        barrel.push_str(&format!("export type * from \"./{name}\";\n"));
    }
    fs::write(dir.join("index.ts"), barrel).expect("write bindings barrel");
}

#[test]
fn export_typescript_bindings() {
    let dir = gen_dir();
    fs::create_dir_all(&dir).expect("create gen directory");
    remove_generated_types(&dir);

    // `export_all_to` follows every referenced type, so these two roots cover
    // the complete JSON contract.
    ClientFrame::export_all_to(&dir).expect("export client bindings");
    ServerFrame::export_all_to(&dir).expect("export server bindings");
    write_barrel(&dir);

    assert!(dir.join("ClientFrame.ts").is_file());
    assert!(dir.join("ServerFrame.ts").is_file());
    assert!(dir.join("AgentState.ts").is_file());
    assert!(dir.join("index.ts").is_file());
}
